  after update of estado, retirada_at on public.mascotas_perdidas
  for each row execute function moderacion_privada.encolar_aviso_estado_mascota();

create function public.reclamar_aviso_estado_mascota(p_id bigint)
returns uuid language plpgsql security definer set search_path = '' as $$
declare v_token uuid := gen_random_uuid();
begin
  if auth.role() is distinct from 'service_role' then raise exception 'Solo el servicio confiable reclama avisos'; end if;
  update public.avisos_estado_mascota set estado='conciliacion',reclamado_hasta=null
    where id=p_id and estado='reclamado' and reclamado_hasta < clock_timestamp()
      and primer_intento_at <= clock_timestamp()-interval '23 hours 55 minutes';
  update public.avisos_estado_mascota set estado='reclamado', token=v_token,
    intentos=intentos+1, primer_intento_at=coalesce(primer_intento_at,clock_timestamp()),
    reclamado_hasta=clock_timestamp()+interval '2 minutes'
    where id=p_id and (estado='pendiente' or (estado='reclamado' and reclamado_hasta < clock_timestamp()))
      and (primer_intento_at is null or primer_intento_at > clock_timestamp()-interval '23 hours 55 minutes');
  if not found then return null; end if;
  return v_token;
end;
$$;
create function public.confirmar_aviso_estado_mascota(p_id bigint,p_token uuid)
returns boolean language plpgsql security definer set search_path = '' as $$
begin
  if auth.role() is distinct from 'service_role' then raise exception 'Solo el servicio confiable confirma avisos'; end if;
  update public.avisos_estado_mascota set estado='enviado',enviado_at=clock_timestamp(),token=null,reclamado_hasta=null
    where id=p_id and estado='reclamado' and token=p_token and p_token is not null and reclamado_hasta>clock_timestamp();
  return found;
end;
$$;
create function public.conciliar_aviso_estado_mascota(p_id bigint,p_token uuid,p_administrador uuid)
returns boolean language plpgsql security definer set search_path = '' as $$
begin
  if auth.role() is distinct from 'service_role' or not exists (
    select 1 from public.profiles p join auth.users u on u.id=p.id
      where p.id=p_administrador and p.rol_id=1 and not coalesce(u.is_anonymous,false)
  ) then return false; end if;
  update public.avisos_estado_mascota set estado='enviado',enviado_at=clock_timestamp(),
    conciliado_at=clock_timestamp(),conciliado_por=p_administrador,token=null
    where id=p_id and estado='conciliacion' and token=p_token and p_token is not null
      and primer_intento_at<=clock_timestamp()-interval '23 hours 55 minutes';
  return found;
end;
$$;
