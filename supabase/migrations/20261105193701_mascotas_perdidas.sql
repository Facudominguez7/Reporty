    where id=p_foto_moderacion_id and decision='APPROVED' and estado='pendiente'
      and estado_publicacion='pendiente' and mascota_id is null
      and not exists (select 1 from public.mascotas_perdidas m where m.foto_moderacion_id=p_foto_moderacion_id);
  if not found then return null; end if;
  return v_token;
end;
$$;

