create function moderacion_privada.encolar_aviso_estado_mascota()
returns trigger language plpgsql security definer set search_path = '' as $$
declare v_evento text; v_email text;
begin
  if old.estado is distinct from new.estado and new.estado='encontrada' then
    v_evento := 'encontrada';
  elsif old.retirada_at is null and new.retirada_at is not null and exists (
    select 1 from public.profiles p where p.id=auth.uid() and p.rol_id=1
  ) then
    v_evento := 'retirada';
  else return new;
  end if;
  select nullif(btrim(u.email),'') into v_email from auth.users u
    where u.id=new.propietario_id and u.is_anonymous is false;
  if v_email is not null then
    insert into public.avisos_estado_mascota(mascota_id,propietario_id,destinatario,evento)
      values (new.id,new.propietario_id,v_email,v_evento);
  end if;
  return new;
end;
$$;
