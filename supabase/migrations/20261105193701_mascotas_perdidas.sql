create table public.mascotas_fotos_moderacion (
  id uuid primary key,
  propietario_id uuid not null references public.profiles(id),
  path_publico text unique,
  path_privado text not null unique,
  hash_sha256 text not null check (hash_sha256 ~ '^[0-9a-f]{64}$'),
  decision text not null default 'REVIEW' check (decision in ('REVIEW','APPROVED','REJECTED')),
  motivos jsonb not null default '[]'::jsonb check (jsonb_typeof(motivos) = 'array'),
  operaciones integer not null default 0 check (operaciones >= 0),
  tipo_animal text not null check (tipo_animal in ('perro','gato','otro')),
  descripcion text not null check (length(btrim(descripcion)) between 1 and 5000),
  lat double precision not null check (lat between -90 and 90),
  lon double precision not null check (lon between -180 and 180),
  telefono text not null check (length(btrim(telefono)) between 1 and 40),
  estado text not null default 'pendiente' check (estado in ('pendiente','aprobada','rechazada')),
  aprobado_at timestamptz,
  creado_at timestamptz not null default clock_timestamp(),
  estado_publicacion text not null default 'pendiente' check (estado_publicacion in ('pendiente','publicando','publicada','rechazada')),
  publish_token uuid,
  mascota_id bigint,
  administrador_id uuid references public.profiles(id),
  revisado_at timestamptz,
  unique (propietario_id, hash_sha256),
  unique (id, propietario_id),
  check (path_privado = propietario_id::text || '/' || id::text),
  check (path_publico is null or path_publico = 'mascotas/' || id::text || '.webp'),
  check ((estado='aprobada') = (aprobado_at is not null)),
  check (estado <> 'aprobada' or decision='APPROVED'),
  check (estado_publicacion not in ('publicando','publicada') or decision='APPROVED'),
  check ((estado_publicacion='publicada') = (path_publico is not null)),
  check ((estado_publicacion='publicando') = (publish_token is not null)),
  check (estado <> 'rechazada' or decision='REJECTED')
);
