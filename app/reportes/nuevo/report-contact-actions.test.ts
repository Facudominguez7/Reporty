import { readFileSync } from "node:fs"
import { describe, expect, it, vi } from "vitest"
import { canShowReportContacts, contactHref, createContactDraft, getReportContacts } from "../../../lib/report-contacts/contact-actions"

describe("report contact actions", () => {
  it("uses shorter cards and buttons and only announces scrolling when the list overflows", () => {
    const actions = readFileSync(new URL("../../../components/report-contact-actions.tsx", import.meta.url), "utf8")
    expect(actions).toContain('size="xs"')
    expect(actions).toContain('bg-card px-2 py-1 text-[0.8rem]')
    expect(actions).toContain('scrollHeight > list.clientHeight')
    expect(actions).toContain('new ResizeObserver')
    expect(actions).toContain('observer.disconnect()')
    expect(actions).toContain('{hasOverflow && <p')
    expect(actions).toContain('Desplazate para ver más organismos')
  })

  it("presents compact contact actions without an editable draft or extra contact text", () => {
    const actions = readFileSync(new URL("../../../components/report-contact-actions.tsx", import.meta.url), "utf8")
    const page = readFileSync(new URL("./page.tsx", import.meta.url), "utf8")
    expect(actions).not.toContain("<Textarea")
    expect(actions).not.toContain("Mensaje editable")
    expect(actions).not.toContain("contact.purpose")
    expect(actions).not.toContain("Contacto sin verificar")
    expect(actions).toContain('<Building2 aria-hidden="true"')
    expect(actions).toContain('max-h-40 space-y-2 overflow-y-auto')
    expect(actions).toContain('tabIndex={0}')
    expect(actions).toContain('aria-label="Lista de organismos"')
    expect(actions).toContain('flex w-full min-w-0 items-center justify-between gap-2')
    expect(actions).toContain('min-w-0 [overflow-wrap:anywhere] font-medium')
    expect(actions).toContain('text-[0.65rem] font-normal text-muted-foreground')
    expect(actions).toContain('{contact.channel_value}')
    expect(actions).toContain('className="shrink-0 whitespace-nowrap"')
    expect(actions).toContain("contact.organization")
    expect(actions).toContain('variant="default"')
    expect(actions).toContain('variant="outline" className="w-full"')
    expect(actions).toContain('<ReportContactActions {...props} reportUrl={reportUrl} showHeading={false} />')
    expect(actions).not.toContain('variant="secondary"')
    expect(actions).toContain('rounded-lg border border-border')
    expect(actions).toContain('aria-label={`${action}: ${contact.organization}`}')
    expect(actions).toContain("contactHref(contact.channel_type, contact.channel_value, draft)")
    expect(actions).toContain("Reporty no envía el mensaje")
    expect(actions).toContain("Cargando contactos")
    expect(actions).toContain("No pudimos cargar los contactos")
    expect(actions).toContain("No hay contactos disponibles")
    expect(page).toContain('variant="ghost-bordered" className="w-full" onClick={startNewReport}')
    expect(page).toContain('<Dialog open={showResultDialog} onOpenChange={handleResultDialogOpenChange}>')
    expect(page).toContain('<DialogTitle')
    expect(page).toContain('<DialogDescription')
    expect(page).toContain('onClick={() => setShowResultDialog(true)}')
    expect(page).toContain('setShowResultDialog(true)')
    expect(page).toContain('grid grid-cols-2 gap-2')
    expect(page).toContain('min-w-0 whitespace-normal [overflow-wrap:anywhere] text-center')
    expect(page.match(/whitespace-normal \[overflow-wrap:anywhere\] text-center/g)).toHaveLength(2)
    expect(page).toContain('!createdReport.withdrawn && <Button')
    expect(page).toContain('createdReport.imageApproved && !createdReport.withdrawn')
    expect(page).toContain('createdReport.isGuest && !createdReport.withdrawn')
    expect(page).toContain('createdReport.imageFailed')
  })
  it("routes every result dialog dismissal to the map while preserving other outcomes", () => {
    const page = readFileSync(new URL("./page.tsx", import.meta.url), "utf8")
    const result = page.slice(page.indexOf("  if (createdReport) {"), page.indexOf("</Dialog>") + "</Dialog>".length)
    expect(result).toContain('<Dialog open={showResultDialog} onOpenChange={handleResultDialogOpenChange}>')
    expect(result).toContain('<DialogContent className="gap-3">')
    expect(result).not.toContain('<DialogClose')
    expect(page).toMatch(/const handleResultDialogOpenChange = \(open: boolean\) => \{\s*setShowResultDialog\(open\)\s*if \(!open\) router\.push\("\/mapa"\)\s*\}/)
    expect(page.match(/router\.push\("\/mapa"\)/g)).toHaveLength(1)
    expect(result).toContain('onClick={startNewReport}')
    expect(result).toContain('{(!createdReport.imageApproved || createdReport.withdrawn) && (')
    expect(result).toContain('<Link href="/mis-reportes">')
    expect(result).toContain('<Link href={`/reportes/${createdReport.reportId}`}>')
    expect(page).toMatch(/const startNewReport = \(\) => \{[\s\S]*?setCreatedReport\(null\)\s*\}/)
    expect(page).toMatch(/if \(!result\.success\) \{[\s\S]*?toast\.error\("Error al crear el reporte"[\s\S]*?return[\s\S]*?\}/)
    expect(page).toContain('result.data.imageModeration?.estado === "REJECTED"')
    expect(page).toContain('moderacion?.estado === "REVIEW" ? "Reporte creado: fotografía pendiente de revisión"')
    expect(page).toContain('moderacion?.estado === "APPROVED" ? "Reporte creado: publicación de fotografía pendiente"')
    expect(page).toContain('const imageFailed = formData.images.length > 0 && !result.data.imageUploaded')
    expect(result).toContain('createdReport.withdrawn ? "Reporte retirado"')
    expect(result).toContain('createdReport.imageFailed &&')
  })

  it("identifies registration in Reporty and passes the public report link to the draft", () => {
    const page = readFileSync(new URL("./page.tsx", import.meta.url), "utf8")
    const actions = readFileSync(new URL("../../../components/report-contact-actions.tsx", import.meta.url), "utf8")
    expect(page).toContain('"Reporte registrado en Reporty"')
    expect(page).not.toContain('"¡Reporte enviado!"')
    expect(page).toContain('reportUrl={`${window.location.origin}/reportes/${createdReport.reportId}`}')
    expect(actions).toContain("createContactDraft(props)")
  })

  it("queries only the resolved municipality and exact category in priority order", async () => {
    const order = vi.fn().mockReturnThis()
    const eq = vi.fn().mockReturnThis()
    const select = vi.fn().mockReturnValue({ eq, order })
    order.mockReturnValueOnce({ order }).mockResolvedValueOnce({ data: [], error: null })
    const from = vi.fn().mockReturnValue({ select })
    await getReportContacts({ from } as never, -27.3676, -55.8961, "Bache")
    expect(from).toHaveBeenCalledWith("report_contact_directory")
    expect(eq.mock.calls).toEqual([["municipality", "Posadas"], ["category", "Bache"]])
    expect(order.mock.calls).toEqual([["priority", { ascending: true }], ["id", { ascending: true }]])
    await getReportContacts({ from } as never, -26, -54, "Bache")
    expect(from).toHaveBeenCalledTimes(1)
  })

  it("only enables contacts for approved and not withdrawn reports", () => {
    expect(canShowReportContacts("APPROVED", false)).toBe(true)
    expect(canShowReportContacts("APPROVED", true)).toBe(false)
    expect(canShowReportContacts("REVIEW", false)).toBe(false)
    expect(canShowReportContacts("REJECTED", false)).toBe(false)
    expect(canShowReportContacts(undefined, false)).toBe(false)
  })

  it("propagates directory errors rather than claiming no contacts", async () => {
    const order = vi.fn().mockReturnThis()
    order.mockReturnValueOnce({ order }).mockResolvedValueOnce({ data: null, error: new Error("offline") })
    const eq = vi.fn().mockReturnThis()
    const client = { from: () => ({ select: () => ({ eq, order }) }) }
    await expect(getReportContacts(client as never, -27.3676, -55.8961, "Bache")).rejects.toThrow("offline")
  })

  it("constructs editable messages and encoded links without assuming publication", () => {
    const draft = createContactDraft({ category: "Bache", description: "Roto & peligroso", latitude: -27, longitude: -55, date: "2026-01-02" })
    expect(draft).toContain("Bache")
    expect(draft).toContain("Roto & peligroso")
    expect(draft).toContain("-27, -55")
    expect(draft).toContain("2026-01-02")
    expect(draft).not.toContain("http")
    expect(createContactDraft({ category: "Bache", description: "x", latitude: -27, longitude: -55, date: "2026-01-02", reportUrl: "https://example.org/reportes/1" })).toContain("https://example.org/reportes/1")
    const fullDraft = createContactDraft({ category: "Bache", description: "Roto & peligroso", latitude: -27, longitude: -55, date: "2026-01-02", reportUrl: "https://example.org/reportes/1" })
    for (const type of ["email", "whatsapp"] as const) {
      const href = contactHref(type, type === "email" ? "a@example.com" : "3764680021", fullDraft)!
      expect(decodeURIComponent(href)).toContain(fullDraft)
    }
    expect(contactHref("email", "a@example.com", draft)).toContain("Roto%20%26%20peligroso")
    expect(contactHref("whatsapp", "3764680021", draft)).toContain("https://wa.me/5493764680021?text=")
    expect(contactHref("whatsapp", "+54 9 376 4680021", draft)).toContain("https://wa.me/5493764680021?text=")
    expect(contactHref("whatsapp", "543764680021", draft)).toContain("https://wa.me/5493764680021?text=")
    expect(contactHref("whatsapp", "5493764680021", draft)).toContain("https://wa.me/5493764680021?text=")
    expect(contactHref("whatsapp", "+12025550123", draft)).toContain("https://wa.me/12025550123?text=")
    expect(contactHref("phone", "3764140677", draft)).toBe("tel:3764140677")
  })
})
