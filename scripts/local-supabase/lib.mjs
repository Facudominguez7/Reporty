/**
 * Live Auth credentials and session state. A copied refresh token or one-time code would still
 * work against production Auth, so they never leave production. Users keep their password hashes.
 */
export const EXCLUDED_TABLES = [
  "auth.sessions",
  "auth.refresh_tokens",
  "auth.mfa_amr_claims",
  "auth.one_time_tokens",
  "auth.flow_state",
  "auth.mfa_challenges",
  "auth.webauthn_challenges",
  "auth.saml_relay_states",
  "auth.oauth_authorizations",
  "auth.oauth_client_states",
  "auth.scim_tokens",
  "auth.audit_log_entries",
]

const SOURCE_FLAGS = { "--production": "production", "--saved": "saved", "--empty": "empty" }

/** @returns {{ source: "ask" | "production" | "saved" | "empty", schema: boolean, help: boolean }} */
export function parseArgs(argv) {
  const options = { source: "ask", schema: false, help: false }

  for (const arg of argv) {
    if (arg in SOURCE_FLAGS) {
      if (options.source !== "ask") throw new Error("Choose only one of --production, --saved or --empty.")
      options.source = SOURCE_FLAGS[arg]
    } else if (arg === "--schema") {
      options.schema = true
    } else if (arg === "-h" || arg === "--help") {
      options.help = true
    } else {
      throw new Error(`Unknown option: ${arg}`)
    }
  }

  if (options.schema && options.source !== "ask") {
    throw new Error("--schema only regenerates the baseline; it takes no data option.")
  }

  return options
}

/** A Postgres URL with a real password, not the dashboard's `[YOUR-PASSWORD]` placeholder. */
export function isConnectionString(value) {
  const text = value.trim()
  if (!/^postgres(ql)?:\/\//.test(text) || text.includes("[YOUR-PASSWORD]")) return false

  try {
    return new URL(text).password !== ""
  } catch {
    return false
  }
}

/**
 * Splits the password out of a connection string. It goes to the CLI through PGPASSWORD, so it
 * never shows up in the arguments that `ps` or the Task Manager list.
 */
export function splitPassword(connectionString) {
  const url = new URL(connectionString.trim())
  const password = decodeURIComponent(url.password)
  url.password = ""
  return { url: url.toString(), password }
}

/** Reads the `KEY="value"` lines printed by `supabase status -o env`; anything else is ignored. */
export function parseStatusEnv(output) {
  const values = {}
  for (const line of output.split(/\r?\n/)) {
    const match = line.match(/^([A-Z][A-Z0-9_]*)="(.*)"$/)
    if (match) values[match[1]] = match[2]
  }
  return values
}

export function readProjectId(configToml) {
  const match = configToml.match(/^project_id\s*=\s*"([^"]+)"/m)
  if (!match) throw new Error("project_id not found in supabase/config.toml")
  return match[1]
}

/**
 * `.env.development.local`: Next.js reads it before `.env.local`, in development only, so the
 * production values stay untouched for builds.
 */
export function envFileContent(status) {
  for (const key of ["API_URL", "ANON_KEY", "SERVICE_ROLE_KEY"]) {
    if (!status[key]) throw new Error(`${key} missing from supabase status`)
  }

  return [
    "# Generated by `npm run db:setup` from `supabase status`. Delete it to develop against production.",
    `NEXT_PUBLIC_SUPABASE_URL=${status.API_URL}`,
    `NEXT_PUBLIC_SUPABASE_ANON_KEY=${status.ANON_KEY}`,
    `SUPABASE_SERVICE_ROLE_KEY=${status.SERVICE_ROLE_KEY}`,
    "NEXT_PUBLIC_APP_URL=http://localhost:3000",
    "# The local Auth has no CAPTCHA, so the widget stays hidden.",
    "NEXT_PUBLIC_TURNSTILE_SITE_KEY=",
    "# The local data may hold real user emails: with no key, report notifications are skipped and logged.",
    "RESEND_API_KEY=",
    "",
  ].join("\n")
}

/** Storage object name → URL path, encoding each segment and keeping the folder slashes. */
export function storagePath(name) {
  return name.split("/").map(encodeURIComponent).join("/")
}

/**
 * Uploading through the Storage API rewrites owner and timestamps; this SQL puts back the values
 * saved before the upload. The JSON goes in a dollar-quoted literal whose tag is not in the data.
 */
export function restoreObjectsSql(bucket, objects) {
  const json = JSON.stringify(objects)
  let tag = "$objects$"
  for (let i = 0; json.includes(tag); i++) tag = `$objects${i}$`

  return `update storage.objects o
set owner = r.owner, owner_id = r.owner_id, created_at = r.created_at, updated_at = r.updated_at
from json_to_recordset(${tag}${json}${tag}) as r(name text, owner uuid, owner_id text, created_at timestamptz, updated_at timestamptz)
where o.bucket_id = '${bucket}' and o.name = r.name;`
}

/** How to get Docker on each platform, shown when it is missing or not running. */
export function dockerHelp(platform) {
  if (platform === "win32") {
    return [
      "Install Docker Desktop for Windows (it uses WSL 2): https://docs.docker.com/desktop/setup/install/windows-install/",
      "Then open Docker Desktop and wait until it says it is running.",
    ].join("\n")
  }
  if (platform === "darwin") {
    return [
      "Install Docker Desktop for Mac: https://docs.docker.com/desktop/setup/install/mac-install/",
      "Then open Docker Desktop from Applications and wait until it says it is running.",
    ].join("\n")
  }
  return [
    "Install Docker Engine: https://docs.docker.com/engine/install/",
    "Then start it (for example `sudo systemctl start docker`) and make sure your user can run `docker ps`.",
  ].join("\n")
}
